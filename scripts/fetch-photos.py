"""Rebuild the bundled food photos and their credits from
scripts/photo-sources.json.

Every photo comes from Wikimedia Commons under a free licence (CC0, public
domain, CC BY or CC BY-SA). The manifest records where each one came from,
who took it and its licence.

  scripts/fetch-photos.py credits    # write assets/images/CREDITS.md and
                                     # assets/images/REUSE.toml
  scripts/fetch-photos.py download   # download, crop to 4:3 and convert to
                                     # WebP with scripts/process-images.sh

To change a photo, edit its entry (source and file from the Commons page,
author, licence and spdx), then run both commands. An optional "crop" of
[left, top, right, bottom] fractions overrides the centred 4:3 crop.

Requirements: python3 and Pillow (pip install pillow).
"""
import io
import json
import subprocess
import sys
import tempfile
import time
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "scripts" / "photo-sources.json"
IMAGES = ROOT / "assets" / "images"
USER_AGENT = "YumMealPrep-asset-fetch/1.0 (https://github.com/ASPTechInc/YumMealPrep)"
SIZE, QUALITY = "1024x768", "78"


def load():
    return json.loads(MANIFEST.read_text(encoding="utf-8"))


def label(key):
    kind, name = key.split(":", 1)
    return f"{name} ({kind})"


def credits(manifest):
    lines = [
        "# Photo credits",
        "",
        "The food photos in YumMealPrep come from Wikimedia Commons and are used under the licences",
        "below. Each was cropped and resized for the app. Tap a link to see the original.",
        "",
    ]
    for key, photo in sorted(manifest.items(), key=lambda kv: label(kv[0]).lower()):
        licence = f"[{photo['licence']}]({photo['licenceUrl']})" if photo.get("licenceUrl") else photo["licence"]
        lines.append(f"- **{label(key)}**: [{photo['file']}]({photo['source']}) by {photo['author']}, {licence}")
    lines.append("")
    (IMAGES / "CREDITS.md").write_text("\n".join(lines), encoding="utf-8")

    reuse = [
        "# Generated by scripts/fetch-photos.py from scripts/photo-sources.json.",
        "# Do not edit by hand. Licensing for the food photos in this folder.",
        "version = 1",
        "",
    ]
    for key, photo in sorted(manifest.items()):
        path = Path(photo["output"]).relative_to("assets/images").as_posix()
        reuse += [
            "[[annotations]]",
            f'path = "{path}"',
            'precedence = "closest"',
            f"SPDX-FileCopyrightText = {json.dumps(photo['author'], ensure_ascii=False)}",
            f'SPDX-License-Identifier = "{photo["spdx"]}"',
            "",
        ]
    (IMAGES / "REUSE.toml").write_text("\n".join(reuse), encoding="utf-8")
    print(f"Wrote credits for {len(manifest)} photos")


def get(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    for attempt in range(5):
        try:
            with urllib.request.urlopen(request, timeout=120) as response:
                return response.read()
        except OSError as error:
            last = error
            time.sleep(3 * (attempt + 1))
    raise last


def download(manifest):
    from PIL import Image, ImageOps

    with tempfile.TemporaryDirectory() as temp:
        sources = Path(temp)
        for key, photo in manifest.items():
            query = urllib.parse.urlencode({
                "action": "query", "format": "json", "prop": "imageinfo",
                "iiprop": "url", "iiurlwidth": 4000 if "crop" in photo else 1600,
                "titles": f"File:{photo['file']}",
            })
            page = next(iter(json.loads(get(f"https://commons.wikimedia.org/w/api.php?{query}"))["query"]["pages"].values()))
            image = ImageOps.exif_transpose(Image.open(io.BytesIO(get(page["imageinfo"][0]["thumburl"])))).convert("RGB")
            width, height = image.size
            if "crop" in photo:
                left, top, right, bottom = photo["crop"]
                image = image.crop((round(left * width), round(top * height), round(right * width), round(bottom * height)))
            elif width / height > 4 / 3:
                new_width = round(height * 4 / 3)
                image = image.crop(((width - new_width) // 2, 0, (width - new_width) // 2 + new_width, height))
            else:
                new_height = round(width * 3 / 4)
                image = image.crop((0, (height - new_height) // 2, width, (height - new_height) // 2 + new_height))
            target = sources / Path(photo["output"]).relative_to("assets/images").with_suffix(".jpg")
            target.parent.mkdir(parents=True, exist_ok=True)
            image.save(target, quality=95)
            print(f"Downloaded {label(key)}", flush=True)
            time.sleep(0.5)
        subprocess.run(
            [str(ROOT / "scripts" / "process-images.sh"), "-F", "-f", "webp", "-s", SIZE, "-p", "1",
             "-q", QUALITY, "-o", str(IMAGES), str(sources)],
            check=True,
        )


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else ""
    if command not in ("credits", "download"):
        sys.exit(__doc__)
    manifest = load()
    download(manifest) if command == "download" else credits(manifest)
